import type { BoneId } from './skeleton';
import type { HitLevel, MoveCategory, MoveDef, Stance } from './moves';

interface StrikeSpec {
  id: string;
  name: string;
  english: string;
  description: string;
  category: MoveCategory;
  input: string;
  from: Stance[];
  totalFrames?: number;
  active?: [number, number];
  bones: BoneId[];
  level?: HitLevel;
  damage?: number;
  stun?: number;
  adv?: number;
  pushback?: number;
  knockdown?: boolean;
  launch?: [number, number, number];
  wallSplat?: boolean;
  groundBounce?: boolean;
  vel?: [number, number, number];
  endStance?: Stance;
  crush?: 'CRUSH_HIGH' | 'CRUSH_LOW' | 'INVULN';
  crushFrames?: [number, number];
  tags?: ('LAUNCHER' | 'SPIN' | 'FLOREIO' | 'THROW')[];
}

function strike(s: StrikeSpec): MoveDef {
  const total = s.totalFrames ?? 30;
  const active = s.active ?? [11, 16];
  const dmg = s.damage ?? 18;
  return {
    id: s.id,
    name: s.name,
    english: s.english,
    description: s.description,
    category: s.category,
    input: s.input,
    from: s.from,
    totalFrames: total,
    poseId: s.id,
    hurtboxOverrides: s.crush ? [{ frames: s.crushFrames ?? [4, total - 8], profile: s.crush }] : undefined,
    hits: [
      {
        frames: active,
        capsules: s.bones.map((bone, i) => ({ bone, radius: i === 0 ? 0.19 : 0.14 })),
        level: s.level ?? 'MID',
        damage: dmg,
        hitstop: Math.min(9, Math.max(4, Math.round(dmg / 3.2))),
        onHit: {
          stun: s.stun ?? 20,
          advantage: s.adv ?? 3,
          pushback: s.pushback ?? 0.9,
          knockdown: s.knockdown,
        },
        onBlock: {
          stun: 13,
          advantage: s.knockdown ? -8 : -4,
          pushback: (s.pushback ?? 0.9) * 0.55,
        },
        launch: s.launch,
        wallSplat: s.wallSplat,
        groundBounce: s.groundBounce,
      },
    ],
    cancels: [
      { into: s.endStance ?? 'GINGA', window: [Math.max(12, active[1] + 2), total - 2], on: 'ALWAYS', input: 'STANCE' },
    ],
    endStance: s.endStance ?? 'GINGA',
    rootMotion: s.vel ? [{ frames: [4, active[1] + 2], vel: s.vel }] : undefined,
    tags: s.tags,
  };
}

interface MotionSpec {
  id: string;
  name: string;
  english: string;
  description: string;
  category: MoveCategory;
  input: string;
  from: Stance[];
  totalFrames?: number;
  endStance?: Stance;
  vel?: [number, number, number];
  crush?: 'CRUSH_HIGH' | 'CRUSH_LOW' | 'INVULN';
  crushFrames?: [number, number];
  tags?: ('LAUNCHER' | 'SPIN' | 'FLOREIO' | 'THROW')[];
}

function floreio(m: MotionSpec): MoveDef {
  const total = m.totalFrames ?? 30;
  return {
    id: m.id,
    name: m.name,
    english: m.english,
    description: m.description,
    category: m.category,
    input: m.input,
    from: m.from,
    totalFrames: total,
    poseId: m.id,
    hurtboxOverrides: m.crush ? [{ frames: m.crushFrames ?? [3, total - 6], profile: m.crush }] : undefined,
    hits: [],
    cancels: [
      { into: m.endStance ?? 'GINGA', window: [Math.floor(total * 0.55), total - 2], on: 'ALWAYS', input: 'STANCE' },
      { into: 'martelo', window: [Math.floor(total * 0.55), total - 2], on: 'ALWAYS', input: 'RK' },
    ],
    endStance: m.endStance ?? 'GINGA',
    rootMotion: m.vel ? [{ frames: [3, total - 6], vel: m.vel }] : undefined,
    tags: m.tags ?? ['FLOREIO'],
  };
}

